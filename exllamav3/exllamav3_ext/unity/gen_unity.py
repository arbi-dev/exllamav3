"""Generate (or --check) the unity translation units in this directory.

WHY. Each host-side launcher file (activation.cu, norm.cu, ...) includes ATen /
c10 headers, and those headers, not the kernels, are most of what it costs to
compile: gcc -E twice, cudafe++, cicc's front end and the host cc1plus all parse
them again for every file. Compiling the launchers a few at a time pays for the
headers once per group instead of once per file. The kernels themselves are
unchanged: each group #includes the original files verbatim, in order, so every
kernel is compiled from the same tokens it was before.

WHAT A GROUP MAY HOLD. Only torch-including launcher files that arbi-serve's
inference never reaches (it serves only LinearEXL3 and the MoE kernels): the
generator/sampling, DeepSeek-V4, n-gram, GDN and
attention/norm/rope launchers of exllamav3's own model stack. Merging files
changes gcc's inlining of host code (a callee shared by more call sites in one
unit is inlined less), so the files on a serving launch path stay separate,
their objects unchanged: exl3_gemm/gemv/gemv_int8, hadamard, hgemm*,
reconstruct, the moe*/coop* launchers, devctx, kernel_map, graph, add,
softcap, pack, util, moe_handoff. Device code is unaffected either way; every
kernel's SASS is the same in or out of a group. The kernel-instance units under
quant/comp_units stay separate as well.

HYGIENE. After each member, every macro that member #defines at file scope is
#undef'd, so one file's private NUM_THREADS etc. never reaches the next. Two
members that define the same file-scope static/anonymous-namespace name do not
compile; split them into different groups.

ext.py and setup.py compile every *.cu here and skip every file a unity unit
names, so a file is compiled exactly once either way.

    python exllamav3/exllamav3_ext/unity/gen_unity.py          # rewrite
    python exllamav3/exllamav3_ext/unity/gen_unity.py --check  # exit 1 if stale
"""

from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EXT = os.path.dirname(HERE)

# Balanced by measured compile cost. Constraints the grouping respects:
#   * two files that include the same header with no include guard
#     (activation_kernels.cuh, parallel/barrier_inner.cuh) are never grouped;
#   * gumbel.cu / sampling_basic.cu / sampling_extra.cu each define gumbel();
#   * norm.cu defines _silu(), as does activation_kernels.cuh;
#   * parallel/{all_reduce,all_reduce_cpu,barrier,broadcast,gather}.cu stay
#     separate: their kernels printf, and the format strings live in a
#     per-module constant bank whose offsets would shift with the neighbours.
GROUPS: list[list[str]] = [
    [
        "activation.cu",
        "gdn.cu",
        "generator/gumbel.cu",
        "moe_unswizzle.cu",
        "ngram.cu",
        "ple.cu",
        "routing.cu",
        "stloader_cu.cu",
    ],
    [
        "attention.cu",
        "dsa_topk.cu",
        "generator/rep_pen.cu",
        "generator/sampling_extra.cu",
        "hc_mix.cu",
        "norm.cu",
        "parallel/context.cu",
        "rope.cu",
    ],
    [
        "cache/q_cache.cu",
        "dsv4_compress.cu",
        "dsv4_pool_quant.cu",
        "generator/cache.cu",
        "generator/dry.cu",
        "generator/sampling_basic.cu",
        "generator/sampling_fused.cu",
        "histogram.cu",
    ],
]

_DEFINE = re.compile(r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_][A-Za-z0-9_]*)", re.M)
_INCLUDE = re.compile(r'^#include "\.\./([^"]+)"$', re.M)


def render(group: list[str]) -> str:
    lines = [
        "// Generated by gen_unity.py; do not edit. One translation unit for the",
        "// torch-including launcher files below (see gen_unity.py for why).",
    ]
    for rel in group:
        with open(os.path.join(EXT, rel), encoding="utf-8") as fh:
            body = fh.read()
        lines.append(f'#include "../{rel}"')
        lines.extend(f"#undef {name}" for name in sorted(set(_DEFINE.findall(body))))
    return "\n".join(lines) + "\n"


def unity_members(directory: str = HERE) -> set[str]:
    """Paths (relative to exllamav3_ext) that a unity unit in ``directory`` compiles."""
    members: set[str] = set()
    for fn in sorted(os.listdir(directory)):
        if fn.endswith(".cu"):
            with open(os.path.join(directory, fn), encoding="utf-8") as fh:
                members.update(_INCLUDE.findall(fh.read()))
    return members


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for i, group in enumerate(GROUPS):
        path = os.path.join(HERE, f"unity_{i}.cu")
        text = render(group)
        try:
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            stale.append(path)
            if not check:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(text)
    extra = sorted(
        fn
        for fn in os.listdir(HERE)
        if fn.endswith(".cu") and fn not in {f"unity_{i}.cu" for i in range(len(GROUPS))}
    )
    for fn in extra:
        stale.append(os.path.join(HERE, fn))
        if not check:
            os.unlink(os.path.join(HERE, fn))
    if check and stale:
        print("stale unity units (run gen_unity.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
